def repair_mojibake(html: str) -> str:
    for broken, fixed in MOJIBAKE_REPLACEMENTS.items():
        html = html.replace(broken, fixed)
    return html


def translate_html_to_english(html: str) -> str:
    html = repair_mojibake(html)
    for turkish, english in TR_TO_EN_REPLACEMENTS.items():
        html = html.replace(turkish, english)
        repaired_turkish = repair_mojibake(turkish)
        if repaired_turkish != turkish:
            html = html.replace(repaired_turkish, english)
    for broken, fixed in ARTIFACT_REPLACEMENTS.items():
        html = html.replace(broken, fixed)
    return html
